"""RAGAS evaluation and A/B benchmark for the group RAG pipeline."""

import argparse
import json
import math
import os
from pathlib import Path

GOLDEN_DATASET_PATH = Path(__file__).parent / "golden_dataset.json"
RESULTS_PATH = Path(__file__).parent / "results.md"
RESULTS_JSON_PATH = Path(__file__).parent / "results.json"


def load_golden_dataset() -> list[dict]:
    with GOLDEN_DATASET_PATH.open(encoding="utf-8") as handle:
        data = json.load(handle)
    if len(data) < 15:
        raise ValueError(f"Golden dataset must contain at least 15 cases; found {len(data)}")
    required = {"question", "expected_answer", "expected_context"}
    for index, item in enumerate(data, 1):
        missing = required - item.keys()
        if missing:
            raise ValueError(f"Case {index} is missing: {sorted(missing)}")
    return data


def collect_cases(golden_dataset: list[dict], use_reranking: bool = True) -> list[dict]:
    """Run the real pipeline and retain all source/output evidence."""
    from src.task9_retrieval_pipeline import retrieve
    from src.task10_generation import format_context, generate_with_citation, reorder_for_llm

    cases = []
    for item in golden_dataset:
        # The production generator currently owns retrieval configuration. The
        # answer is always generated by the real pipeline, never synthesized.
        generated = generate_with_citation(item["question"], top_k=5, use_reranking=use_reranking)
        sources = generated.get("sources", [])
        if not sources:
            sources = retrieve(item["question"], top_k=5, use_reranking=use_reranking)
        context = format_context(reorder_for_llm(sources)) if sources else ""
        cases.append({
            "question": item["question"],
            "answer": generated.get("answer", ""),
            "expected_answer": item["expected_answer"],
            "expected_context": item["expected_context"],
            "contexts": [source.get("content", "") for source in sources],
            "sources": sources,
            "formatted_context": context,
        })
    return cases


def evaluate_with_ragas(cases: list[dict]) -> dict:
    """Evaluate collected cases with RAGAS; provider errors are surfaced."""
    from datasets import Dataset
    from ragas import evaluate
    from ragas.metrics import answer_relevancy, context_precision, context_recall, faithfulness

    dataset = Dataset.from_dict({
        "question": [case["question"] for case in cases],
        "answer": [case["answer"] for case in cases],
        "contexts": [case["contexts"] for case in cases],
        "ground_truth": [case["expected_answer"] for case in cases],
    })
    from langchain_openai import ChatOpenAI, OpenAIEmbeddings

    llm = ChatOpenAI(
        model="openai/gpt-4o-mini",
        base_url="https://openrouter.ai/api/v1",
        api_key=os.getenv("OPENROUTER_API_KEY"),
        temperature=0,
        max_tokens=512,
    )
    embeddings = OpenAIEmbeddings(
        model="openai/text-embedding-3-small",
        base_url="https://openrouter.ai/api/v1",
        api_key=os.getenv("OPENROUTER_API_KEY"),
    )
    result = evaluate(
        dataset,
        metrics=[faithfulness, answer_relevancy, context_recall, context_precision],
        llm=llm,
        embeddings=embeddings,
        raise_exceptions=True,
    )
    scores = {key: float(value) for key, value in result.items() if isinstance(value, (int, float))}
    invalid = [key for key, value in scores.items() if math.isnan(value) or math.isinf(value)]
    if invalid:
        raise RuntimeError(f"RAGAS returned invalid NaN/Inf scores: {invalid}")
    rows = result.to_pandas().to_dict("records") if hasattr(result, "to_pandas") else []
    return {"overall": scores, "rows": rows}


def compare_configs(golden_dataset: list[dict]) -> dict:
    """Run the same cases with reranking enabled and disabled."""
    comparison = {}
    for name, use_reranking in (("hybrid_rerank", True), ("hybrid_no_rerank", False)):
        cases = collect_cases(golden_dataset, use_reranking=use_reranking)
        ragas = evaluate_with_ragas(cases)
        comparison[name] = {
            "cases": cases,
            "retrieval_hit_rate": sum(bool(case["contexts"]) for case in cases) / len(cases),
            "ragas": ragas,
        }
    return comparison


def export_results(comparison: dict, metrics: dict | None = None, error: str | None = None) -> None:
    json_result = {
        "framework": "RAGAS",
        "dataset_cases": sum(len(value.get("cases", [])) for value in comparison.values()) // max(len(comparison), 1),
        "runtime_status": "BLOCKED" if error else ("COMPLETED" if metrics else "INCOMPLETE"),
        "metrics": metrics or {},
        "ab_comparison": {
            name: {"retrieval_hit_rate": value.get("retrieval_hit_rate")}
            for name, value in comparison.items()
        },
        "error": error,
    }
    RESULTS_JSON_PATH.write_text(
        json.dumps(json_result, ensure_ascii=False, indent=2, default=str),
        encoding="utf-8",
    )

    # Keep results.md user-editable. The evaluation run only owns results.json.
    return

    # Legacy Markdown exporter retained below for reference.
    lines = ["# RAG Evaluation Results", "", "## Framework sử dụng", "", "> RAGAS với OpenRouter làm LLM judge.", "", "- Dataset cases: 15", ""]
    if error:
        lines += ["**Runtime status:** BLOCKED", "", f"`{error}`", "", "No metric scores were invented.", ""]
    elif metrics:
        lines += ["**Runtime status:** COMPLETED", "", "## Overall Scores", "", "| Metric | Config A: Hybrid + Rerank | Config B: Hybrid without Rerank |", "|---|---:|---:|"]
        for key in ("faithfulness", "answer_relevancy", "context_recall", "context_precision"):
            lines.append(f"| {key} | {metrics['hybrid_rerank']['overall'].get(key, 'N/A')} | {metrics['hybrid_no_rerank']['overall'].get(key, 'N/A')} |")
        lines += ["", "## A/B Comparison Analysis", "", "| Config | Retrieval hit rate |", "|---|---:|"]
        for name, result in comparison.items():
            lines.append(f"| {name} | {result['retrieval_hit_rate']:.3f} |")
        lines += ["", "Scores above were returned by RAGAS using the configured OpenRouter judge.", "", "## Worst Performers (Bottom 3)", "", "| Config | Case |", "|---|---|"]
        for name, result in metrics.items():
            rows = result.get("rows", [])
            for row in rows[:3]:
                lines.append(f"| {name} | {row.get('user_input', row.get('question', 'unknown'))} |")
        lines += ["", "## Root Cause Analysis", "", "Low answer relevance indicates that generated answers should be shorter and more directly aligned with the question. Cases with low faithfulness require source and citation review.", "", "## Recommendations", "", "1. Improve the generation prompt to answer only the requested fact before adding explanation.", "2. Add source-grounding validation for every citation.", "3. Inspect low-scoring cases and tune chunking/retrieval for the affected source documents.", ""]
    else:
        lines += ["**Runtime status:** COMPLETED", "", "## A/B Comparison Analysis", "", "| Config | Retrieval hit rate |", "|---|---:|"]
        for name, result in comparison.items():
            lines.append(f"| {name} | {result['retrieval_hit_rate']:.3f} |")
        lines += ["", "Full RAGAS metric scores should be appended from the successful API run.", ""]
    lines += ["## QA Notes", "", "- Compare only runs using the same golden dataset and source snapshot.", "- Keep provider, fallback, and grounding failures separate.", "- Do not report a failed provider call as an AI success.", ""]
    RESULTS_PATH.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--limit", type=int, default=None, help="Run only a subset for smoke testing")
    args = parser.parse_args()
    golden = load_golden_dataset()
    if args.limit:
        golden = golden[:args.limit]
    print(f"Loaded {len(golden)} golden cases")
    try:
        comparison = compare_configs(golden)
        export_results(
            comparison,
            metrics={name: value["ragas"] for name, value in comparison.items()},
        )
        print(f"Wrote {RESULTS_JSON_PATH}")
    except Exception as exc:
        export_results({}, error=str(exc))
        raise


if __name__ == "__main__":
    main()
